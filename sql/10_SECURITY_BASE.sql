CREATE TABLE RM_CFACT_ROLE (
    ROLE_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ROLE_CODE     VARCHAR2(40) NOT NULL,
    ROLE_NAME     VARCHAR2(120) NOT NULL,
    ACTIVE        CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_RMCF_ROLE_CODE UNIQUE (ROLE_CODE),
    CONSTRAINT CK_RMCF_ROLE_ACT CHECK (ACTIVE IN ('Y','N'))
);

CREATE TABLE RM_CFACT_PERMISSION (
    PERMISSION_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PERMISSION_CODE  VARCHAR2(80) NOT NULL,
    PERMISSION_NAME  VARCHAR2(160) NOT NULL,
    ACTIVE           CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_RMCF_PERM_CODE UNIQUE (PERMISSION_CODE),
    CONSTRAINT CK_RMCF_PERM_ACT CHECK (ACTIVE IN ('Y','N'))
);

CREATE TABLE RM_CFACT_ROLE_PERMISSION (
    ROLE_ID        NUMBER NOT NULL,
    PERMISSION_ID  NUMBER NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RMCF_ROLE_PERM PRIMARY KEY (ROLE_ID, PERMISSION_ID),
    CONSTRAINT FK_RMCF_RP_ROLE FOREIGN KEY (ROLE_ID) REFERENCES RM_CFACT_ROLE(ROLE_ID),
    CONSTRAINT FK_RMCF_RP_PERM FOREIGN KEY (PERMISSION_ID) REFERENCES RM_CFACT_PERMISSION(PERMISSION_ID)
);

CREATE TABLE RM_CFACT_USER (
    USER_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USERNAME       VARCHAR2(120) NOT NULL,
    DISPLAY_NAME   VARCHAR2(200) NOT NULL,
    EMAIL          VARCHAR2(200),
    ROLE_ID        NUMBER NOT NULL,
    PASSWORD_HASH  VARCHAR2(500),
    ACTIVE         CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY     VARCHAR2(120),
    UPDATED_AT     TIMESTAMP,
    UPDATED_BY     VARCHAR2(120),
    CONSTRAINT UQ_RMCF_USER_NAME UNIQUE (USERNAME),
    CONSTRAINT CK_RMCF_USER_ACT CHECK (ACTIVE IN ('Y','N')),
    CONSTRAINT FK_RMCF_USER_ROLE FOREIGN KEY (ROLE_ID) REFERENCES RM_CFACT_ROLE(ROLE_ID)
);

CREATE TABLE RM_CFACT_USER_AUTH (
    USER_ID             NUMBER PRIMARY KEY,
    AUTH_TYPE           VARCHAR2(20) DEFAULT 'LDAP' NOT NULL,
    LDAP_USERNAME       VARCHAR2(200),
    SESSION_VERSION     NUMBER DEFAULT 1 NOT NULL,
    FAILED_ATTEMPTS     NUMBER DEFAULT 0 NOT NULL,
    LOCKED_UNTIL        TIMESTAMP,
    LAST_LOGIN_SUCCESS  TIMESTAMP,
    LAST_LOGIN_FAILURE  TIMESTAMP,
    UPDATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_RMCF_UA_USER FOREIGN KEY (USER_ID) REFERENCES RM_CFACT_USER(USER_ID) ON DELETE CASCADE,
    CONSTRAINT CK_RMCF_UA_TYPE CHECK (AUTH_TYPE IN ('LDAP','LOCAL','SERVICE')),
    CONSTRAINT CK_RMCF_UA_VER CHECK (SESSION_VERSION >= 1),
    CONSTRAINT CK_RMCF_UA_FAIL CHECK (FAILED_ATTEMPTS >= 0)
);

CREATE TABLE RM_CFACT_USER_PERMISSION (
    USER_ID        NUMBER NOT NULL,
    PERMISSION_ID  NUMBER NOT NULL,
    ALLOW_FLAG     CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RMCF_USER_PERM PRIMARY KEY (USER_ID, PERMISSION_ID),
    CONSTRAINT FK_RMCF_UP_USER FOREIGN KEY (USER_ID) REFERENCES RM_CFACT_USER(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_RMCF_UP_PERM FOREIGN KEY (PERMISSION_ID) REFERENCES RM_CFACT_PERMISSION(PERMISSION_ID),
    CONSTRAINT CK_RMCF_UP_ALLOW CHECK (ALLOW_FLAG IN ('Y','N'))
);

CREATE TABLE RM_CFACT_LOGIN_RATE_LIMIT (
    ORIGIN_IP          VARCHAR2(64) PRIMARY KEY,
    FAILED_ATTEMPTS    NUMBER DEFAULT 0 NOT NULL,
    WINDOW_STARTED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    LOCKED_UNTIL       TIMESTAMP,
    UPDATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_RMCF_LRL_FAIL CHECK (FAILED_ATTEMPTS >= 0)
);

CREATE TABLE RM_CFACT_AUDIT_LOG (
    AUDIT_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    EVENT_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    USER_ID       NUMBER,
    MODULE_NAME   VARCHAR2(80) NOT NULL,
    ENTITY_NAME   VARCHAR2(80) NOT NULL,
    ENTITY_ID     VARCHAR2(120),
    ACTION_NAME   VARCHAR2(40) NOT NULL,
    BEFORE_DATA   CLOB,
    AFTER_DATA    CLOB,
    CLIENT_IP     VARCHAR2(64),
    CONSTRAINT FK_RMCF_AUD_USER FOREIGN KEY (USER_ID) REFERENCES RM_CFACT_USER(USER_ID)
);

CREATE INDEX IX_RMCF_USER_ROLE ON RM_CFACT_USER(ROLE_ID, ACTIVE);
CREATE INDEX IX_RMCF_UA_LOCK ON RM_CFACT_USER_AUTH(LOCKED_UNTIL);
CREATE INDEX IX_RMCF_AUD_EVENT ON RM_CFACT_AUDIT_LOG(EVENT_AT);
CREATE INDEX IX_RMCF_AUD_USER ON RM_CFACT_AUDIT_LOG(USER_ID, EVENT_AT);

