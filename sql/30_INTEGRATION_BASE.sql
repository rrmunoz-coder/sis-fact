/* ============================================================
   BILLING ONE / SIS-FACT v0.2.1
   30_INTEGRATION_BASE.sql
   Catálogo administrable de conexiones técnicas, insumos y alcances.
   El origen funcional se resuelve desde RM_CFACT_SCOPE; no se duplica
   en la conexión técnica. Los secretos NO se almacenan en CONFIG_JSON;
   CREDENTIAL_REF apunta a configuración/gestor de secretos externo.
   ============================================================ */

CREATE TABLE RM_CFACT_CONNECTION (
    CONNECTION_ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CONNECTION_CODE   VARCHAR2(80) NOT NULL,
    CONNECTION_NAME   VARCHAR2(200) NOT NULL,
    CONNECTION_TYPE   VARCHAR2(20) NOT NULL,
    CREDENTIAL_REF    VARCHAR2(160),
    CONFIG_JSON       CLOB,
    ACTIVE            CHAR(1) DEFAULT 'Y' NOT NULL,
    HEALTH_STATUS     VARCHAR2(30),
    LAST_TEST_AT      TIMESTAMP,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY        VARCHAR2(120),
    UPDATED_AT        TIMESTAMP,
    UPDATED_BY        VARCHAR2(120),
    CONSTRAINT UQ_RMCF_CONN_CODE UNIQUE (CONNECTION_CODE),
    CONSTRAINT CK_RMCF_CONN_TYPE CHECK (CONNECTION_TYPE IN ('ORACLE','SQLSERVER','REST','SOAP','FILE')),
    CONSTRAINT CK_RMCF_CONN_ACT CHECK (ACTIVE IN ('Y','N'))
);

CREATE TABLE RM_CFACT_CONNECTION_SCOPE (
    CONNECTION_SCOPE_ID  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CONNECTION_ID        NUMBER NOT NULL,
    SCOPE_ID             NUMBER NOT NULL,
    ACTIVE               CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_RMCF_CONN_SCOPE UNIQUE (CONNECTION_ID, SCOPE_ID),
    CONSTRAINT FK_RMCF_CS_CONN FOREIGN KEY (CONNECTION_ID) REFERENCES RM_CFACT_CONNECTION(CONNECTION_ID) ON DELETE CASCADE,
    CONSTRAINT FK_RMCF_CS_SCOPE FOREIGN KEY (SCOPE_ID) REFERENCES RM_CFACT_SCOPE(SCOPE_ID) ON DELETE CASCADE,
    CONSTRAINT CK_RMCF_CS_ACT CHECK (ACTIVE IN ('Y','N'))
);

CREATE TABLE RM_CFACT_DATA_SOURCE (
    DATA_SOURCE_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SOURCE_CODE         VARCHAR2(80) NOT NULL,
    SOURCE_NAME         VARCHAR2(200) NOT NULL,
    LOGICAL_TYPE        VARCHAR2(80) NOT NULL,
    CONNECTION_ID       NUMBER NOT NULL,
    EXTRACTION_TYPE     VARCHAR2(20) NOT NULL,
    DEFINITION_TEXT     CLOB,
    EXPECTED_FREQUENCY  VARCHAR2(40),
    CRITICAL_FLAG       CHAR(1) DEFAULT 'N' NOT NULL,
    ACTIVE              CHAR(1) DEFAULT 'Y' NOT NULL,
    OWNER_USER_ID       NUMBER,
    LAST_SUCCESS_AT     TIMESTAMP,
    CREATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY          VARCHAR2(120),
    UPDATED_AT          TIMESTAMP,
    UPDATED_BY          VARCHAR2(120),
    CONSTRAINT UQ_RMCF_DS_CODE UNIQUE (SOURCE_CODE),
    CONSTRAINT FK_RMCF_DS_CONN FOREIGN KEY (CONNECTION_ID) REFERENCES RM_CFACT_CONNECTION(CONNECTION_ID),
    CONSTRAINT FK_RMCF_DS_OWNER FOREIGN KEY (OWNER_USER_ID) REFERENCES RM_CFACT_USER(USER_ID),
    CONSTRAINT CK_RMCF_DS_EXT CHECK (EXTRACTION_TYPE IN ('SQL','REST','SOAP','FILE')),
    CONSTRAINT CK_RMCF_DS_CRIT CHECK (CRITICAL_FLAG IN ('Y','N')),
    CONSTRAINT CK_RMCF_DS_ACT CHECK (ACTIVE IN ('Y','N'))
);

CREATE TABLE RM_CFACT_DATA_SOURCE_PARAM (
    PARAM_ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DATA_SOURCE_ID    NUMBER NOT NULL,
    PARAM_NAME        VARCHAR2(80) NOT NULL,
    PARAM_TYPE        VARCHAR2(30) DEFAULT 'STRING' NOT NULL,
    VALUE_SOURCE      VARCHAR2(20) DEFAULT 'RUNTIME' NOT NULL,
    CONTEXT_FIELD     VARCHAR2(40),
    DEFAULT_VALUE     VARCHAR2(1000),
    REQUIRED_FLAG     CHAR(1) DEFAULT 'N' NOT NULL,
    ACTIVE            CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT UQ_RMCF_DSP_NAME UNIQUE (DATA_SOURCE_ID, PARAM_NAME),
    CONSTRAINT FK_RMCF_DSP_DS FOREIGN KEY (DATA_SOURCE_ID) REFERENCES RM_CFACT_DATA_SOURCE(DATA_SOURCE_ID) ON DELETE CASCADE,
    CONSTRAINT CK_RMCF_DSP_SRC CHECK (VALUE_SOURCE IN ('CONTEXT','STATIC','RUNTIME')),
    CONSTRAINT CK_RMCF_DSP_REQ CHECK (REQUIRED_FLAG IN ('Y','N')),
    CONSTRAINT CK_RMCF_DSP_ACT CHECK (ACTIVE IN ('Y','N'))
);

CREATE TABLE RM_CFACT_SOURCE_SCOPE (
    SOURCE_SCOPE_ID  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DATA_SOURCE_ID   NUMBER NOT NULL,
    SCOPE_ID         NUMBER NOT NULL,
    PRIORITY_ORDER   NUMBER DEFAULT 100 NOT NULL,
    ACTIVE           CHAR(1) DEFAULT 'Y' NOT NULL,
    VALID_FROM       DATE,
    VALID_TO         DATE,
    CREATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_RMCF_SRC_SCOPE UNIQUE (DATA_SOURCE_ID, SCOPE_ID),
    CONSTRAINT FK_RMCF_SS_DS FOREIGN KEY (DATA_SOURCE_ID) REFERENCES RM_CFACT_DATA_SOURCE(DATA_SOURCE_ID) ON DELETE CASCADE,
    CONSTRAINT FK_RMCF_SS_SCOPE FOREIGN KEY (SCOPE_ID) REFERENCES RM_CFACT_SCOPE(SCOPE_ID) ON DELETE CASCADE,
    CONSTRAINT CK_RMCF_SS_PRIO CHECK (PRIORITY_ORDER >= 0),
    CONSTRAINT CK_RMCF_SS_ACT CHECK (ACTIVE IN ('Y','N')),
    CONSTRAINT CK_RMCF_SS_DATES CHECK (VALID_TO IS NULL OR VALID_FROM IS NULL OR VALID_TO >= VALID_FROM)
);

CREATE TABLE RM_CFACT_EXTRACTION_RUN (
    EXTRACTION_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DATA_SOURCE_ID     NUMBER NOT NULL,
    SCOPE_ID           NUMBER,
    PERIOD_CODE        VARCHAR2(30),
    EXECUTION_CODE     VARCHAR2(120),
    CORRELATION_ID     VARCHAR2(120),
    STARTED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FINISHED_AT        TIMESTAMP,
    ROWS_READ          NUMBER DEFAULT 0 NOT NULL,
    ROWS_LOADED        NUMBER DEFAULT 0 NOT NULL,
    ROWS_REJECTED      NUMBER DEFAULT 0 NOT NULL,
    STATUS             VARCHAR2(30) DEFAULT 'RUNNING' NOT NULL,
    ERROR_STAGE        VARCHAR2(60),
    ERROR_MESSAGE      VARCHAR2(4000),
    DEFINITION_VERSION VARCHAR2(80),
    CONSTRAINT FK_RMCF_ER_DS FOREIGN KEY (DATA_SOURCE_ID) REFERENCES RM_CFACT_DATA_SOURCE(DATA_SOURCE_ID),
    CONSTRAINT FK_RMCF_ER_SCOPE FOREIGN KEY (SCOPE_ID) REFERENCES RM_CFACT_SCOPE(SCOPE_ID),
    CONSTRAINT CK_RMCF_ER_STATUS CHECK (STATUS IN ('CREATED','RUNNING','SUCCESS','WARNING','ERROR')),
    CONSTRAINT CK_RMCF_ER_ROWS CHECK (ROWS_READ >= 0 AND ROWS_LOADED >= 0 AND ROWS_REJECTED >= 0)
);

CREATE TABLE RM_CFACT_INTEGRATION_CALL (
    INTEGRATION_CALL_ID  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DATA_SOURCE_ID       NUMBER NOT NULL,
    EXTRACTION_ID        NUMBER,
    CORRELATION_ID       VARCHAR2(120),
    ENDPOINT_NAME        VARCHAR2(160),
    OPERATION_NAME       VARCHAR2(160),
    STARTED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FINISHED_AT          TIMESTAMP,
    RESPONSE_TIME_MS     NUMBER,
    TECHNICAL_STATUS     VARCHAR2(40),
    BUSINESS_STATUS      VARCHAR2(80),
    HTTP_STATUS          NUMBER,
    RESPONSE_CODE        VARCHAR2(120),
    RETRY_NUMBER         NUMBER DEFAULT 0 NOT NULL,
    REQUEST_HASH         VARCHAR2(200),
    ERROR_MESSAGE        VARCHAR2(4000),
    CONSTRAINT FK_RMCF_IC_DS FOREIGN KEY (DATA_SOURCE_ID) REFERENCES RM_CFACT_DATA_SOURCE(DATA_SOURCE_ID),
    CONSTRAINT FK_RMCF_IC_ER FOREIGN KEY (EXTRACTION_ID) REFERENCES RM_CFACT_EXTRACTION_RUN(EXTRACTION_ID),
    CONSTRAINT CK_RMCF_IC_RETRY CHECK (RETRY_NUMBER >= 0)
);

CREATE TABLE RM_CFACT_CONNECTION_TEST (
    CONNECTION_TEST_ID  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CONNECTION_ID       NUMBER NOT NULL,
    TESTED_BY            NUMBER,
    TESTED_AT            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FINISHED_AT          TIMESTAMP,
    STATUS               VARCHAR2(30) NOT NULL,
    RESPONSE_TIME_MS     NUMBER,
    DETAIL               VARCHAR2(2000),
    CONSTRAINT FK_RMCF_CT_CONN FOREIGN KEY (CONNECTION_ID) REFERENCES RM_CFACT_CONNECTION(CONNECTION_ID) ON DELETE CASCADE,
    CONSTRAINT FK_RMCF_CT_USER FOREIGN KEY (TESTED_BY) REFERENCES RM_CFACT_USER(USER_ID),
    CONSTRAINT CK_RMCF_CT_STATUS CHECK (STATUS IN ('SUCCESS','WARNING','ERROR'))
);

CREATE INDEX IX_RMCF_CS_SCOPE ON RM_CFACT_CONNECTION_SCOPE(SCOPE_ID, CONNECTION_ID);
CREATE INDEX IX_RMCF_DS_CONN ON RM_CFACT_DATA_SOURCE(CONNECTION_ID, ACTIVE);
CREATE INDEX IX_RMCF_SS_SCOPE ON RM_CFACT_SOURCE_SCOPE(SCOPE_ID, ACTIVE, PRIORITY_ORDER);
CREATE INDEX IX_RMCF_ER_SRC ON RM_CFACT_EXTRACTION_RUN(DATA_SOURCE_ID, STARTED_AT);
CREATE INDEX IX_RMCF_ER_CORR ON RM_CFACT_EXTRACTION_RUN(CORRELATION_ID);
CREATE INDEX IX_RMCF_IC_CORR ON RM_CFACT_INTEGRATION_CALL(CORRELATION_ID);
CREATE INDEX IX_RMCF_CT_CONN ON RM_CFACT_CONNECTION_TEST(CONNECTION_ID, TESTED_AT);

COMMENT ON TABLE RM_CFACT_CONNECTION IS 'Conexiones técnicas administrables. CONFIG_JSON no debe contener secretos.';
COMMENT ON COLUMN RM_CFACT_CONNECTION.CREDENTIAL_REF IS 'Referencia a credencial externa; nunca contraseña en texto plano.';
COMMENT ON TABLE RM_CFACT_DATA_SOURCE IS 'Insumo funcional obtenido mediante una conexión técnica.';
COMMENT ON COLUMN RM_CFACT_DATA_SOURCE.LOGICAL_TYPE IS 'Concepto funcional: DOCUMENTOS_FACTURADOS, ESTADO_SII, PAGOS, ACTIVOS, etc.';
COMMENT ON TABLE RM_CFACT_SOURCE_SCOPE IS 'Define en qué scope RUT/negocio/origen/tipo/flujo aplica un insumo.';

COMMIT;
