   Primera capa de resultado operacional de emisión.

   Los indicadores NO son dimensiones de contexto.
   Se registran como resultado por SCOPE / periodo / segmento.
   ============================================================ */

CREATE TABLE RM_CFACT_EMISSION_STATUS (
    EMISSION_STATUS_ID  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SCOPE_ID            NUMBER NOT NULL,
    EXTRACTION_ID       NUMBER,
    PERIOD_CODE         VARCHAR2(30),
    SEGMENT_VALUE       VARCHAR2(120),
    STATUS_CODE         VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    COMPLETENESS_PCT    NUMBER(7,4),
    EXPECTED_QTY        NUMBER DEFAULT 0 NOT NULL,
    EMITTED_QTY         NUMBER DEFAULT 0 NOT NULL,
    REJECTED_QTY        NUMBER DEFAULT 0 NOT NULL,
    ISSUE_QTY           NUMBER DEFAULT 0 NOT NULL,
    AMOUNT_TOTAL        NUMBER(20,2),
    MEASURED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DETAIL_JSON         CLOB,
    CREATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_RMCF_ES_SCOPE FOREIGN KEY (SCOPE_ID) REFERENCES RM_CFACT_SCOPE(SCOPE_ID),
    CONSTRAINT FK_RMCF_ES_EXT FOREIGN KEY (EXTRACTION_ID) REFERENCES RM_CFACT_EXTRACTION_RUN(EXTRACTION_ID),
    CONSTRAINT CK_RMCF_ES_STATUS CHECK (STATUS_CODE IN ('PENDING','RUNNING','OK','WARNING','ERROR','BLOCKED')),
    CONSTRAINT CK_RMCF_ES_PCT CHECK (COMPLETENESS_PCT IS NULL OR (COMPLETENESS_PCT >= 0 AND COMPLETENESS_PCT <= 100)),
    CONSTRAINT CK_RMCF_ES_QTY CHECK (EXPECTED_QTY >= 0 AND EMITTED_QTY >= 0 AND REJECTED_QTY >= 0 AND ISSUE_QTY >= 0)
);

CREATE TABLE RM_CFACT_ISSUE (
    ISSUE_ID             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    EMISSION_STATUS_ID   NUMBER NOT NULL,
    ISSUE_CODE           VARCHAR2(80),
    SEVERITY             VARCHAR2(20) DEFAULT 'MEDIUM' NOT NULL,
    TITLE                VARCHAR2(250) NOT NULL,
    DETAIL_TEXT          VARCHAR2(4000),
    ISSUE_STATUS         VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    DETECTED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    RESOLVED_AT          TIMESTAMP,
    CREATED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_RMCF_ISSUE_STATUS FOREIGN KEY (EMISSION_STATUS_ID)
        REFERENCES RM_CFACT_EMISSION_STATUS(EMISSION_STATUS_ID) ON DELETE CASCADE,
    CONSTRAINT CK_RMCF_ISSUE_SEV CHECK (SEVERITY IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    CONSTRAINT CK_RMCF_ISSUE_STATE CHECK (ISSUE_STATUS IN ('OPEN','ACKNOWLEDGED','RESOLVED','DISMISSED')),
    CONSTRAINT CK_RMCF_ISSUE_DATES CHECK (RESOLVED_AT IS NULL OR RESOLVED_AT >= DETECTED_AT)
);

CREATE INDEX IX_RMCF_ES_SCOPE ON RM_CFACT_EMISSION_STATUS(SCOPE_ID, PERIOD_CODE, MEASURED_AT);
CREATE INDEX IX_RMCF_ES_STATUS ON RM_CFACT_EMISSION_STATUS(STATUS_CODE, MEASURED_AT);
CREATE INDEX IX_RMCF_ISSUE_ES ON RM_CFACT_ISSUE(EMISSION_STATUS_ID, ISSUE_STATUS, SEVERITY);

COMMENT ON TABLE RM_CFACT_EMISSION_STATUS IS 'Snapshot de estado de facturación por alcance, periodo y segmento operativo.';
COMMENT ON COLUMN RM_CFACT_EMISSION_STATUS.SEGMENT_VALUE IS 'Valor runtime del segmentador definido por el flujo, por ejemplo DOM 22 o CICLO 22.';
COMMENT ON COLUMN RM_CFACT_EMISSION_STATUS.COMPLETENESS_PCT IS 'Completitud entre 0 y 100.';
COMMENT ON TABLE RM_CFACT_ISSUE IS 'Detalle opcional de issues detectados para un estado de emisión.';

COMMIT;
