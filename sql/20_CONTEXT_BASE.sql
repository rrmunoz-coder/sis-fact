/* ============================================================
   BILLING ONE / SIS-FACT v0.2.3
   20_CONTEXT_BASE.sql
   Contexto funcional de facturación.

   Jerarquía operativa:
   RUT emisor -> Negocio -> Origen -> Tipo de emisión -> Flujo opcional

   DOM y Ciclo NO son dimensiones universales. Se expresan mediante
   RM_CFACT_FLOW.SEGMENT_LABEL cuando corresponda al origen.
   ============================================================ */

CREATE TABLE RM_CFACT_COMPANY (
    COMPANY_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    COMPANY_CODE  VARCHAR2(40) NOT NULL,
    COMPANY_NAME  VARCHAR2(200) NOT NULL,
    ACTIVE        CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_RMCF_COMP_CODE UNIQUE (COMPANY_CODE),
    CONSTRAINT CK_RMCF_COMP_ACT CHECK (ACTIVE IN ('Y','N'))
);

CREATE TABLE RM_CFACT_ISSUER (
    ISSUER_ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    COMPANY_ID    NUMBER,
    TAX_ID        VARCHAR2(20) NOT NULL,
    LEGAL_NAME    VARCHAR2(250) NOT NULL,
    ACTIVE        CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_RMCF_ISS_TAX UNIQUE (TAX_ID),
    CONSTRAINT FK_RMCF_ISS_COMP FOREIGN KEY (COMPANY_ID) REFERENCES RM_CFACT_COMPANY(COMPANY_ID),
    CONSTRAINT CK_RMCF_ISS_ACT CHECK (ACTIVE IN ('Y','N'))
);

CREATE TABLE RM_CFACT_BUSINESS (
    BUSINESS_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    BUSINESS_CODE  VARCHAR2(60) NOT NULL,
    BUSINESS_NAME  VARCHAR2(160) NOT NULL,
    ACTIVE         CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_RMCF_BUS_CODE UNIQUE (BUSINESS_CODE),
    CONSTRAINT CK_RMCF_BUS_ACT CHECK (ACTIVE IN ('Y','N'))
);

CREATE TABLE RM_CFACT_ORIGIN (
    ORIGIN_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ORIGIN_CODE  VARCHAR2(60) NOT NULL,
    ORIGIN_NAME  VARCHAR2(160) NOT NULL,
    ACTIVE       CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_RMCF_ORIGIN_CODE UNIQUE (ORIGIN_CODE),
    CONSTRAINT CK_RMCF_ORIGIN_ACT CHECK (ACTIVE IN ('Y','N'))
);

CREATE TABLE RM_CFACT_EMISSION_TYPE (
    EMISSION_TYPE_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    EMISSION_TYPE_CODE  VARCHAR2(40) NOT NULL,
    EMISSION_TYPE_NAME  VARCHAR2(120) NOT NULL,
    ACTIVE              CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_RMCF_EMTYPE_CODE UNIQUE (EMISSION_TYPE_CODE),
    CONSTRAINT CK_RMCF_EMTYPE_ACT CHECK (ACTIVE IN ('Y','N'))
);

CREATE TABLE RM_CFACT_FLOW (
    FLOW_ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ORIGIN_ID          NUMBER NOT NULL,
    EMISSION_TYPE_ID   NUMBER NOT NULL,
    FLOW_CODE          VARCHAR2(80) NOT NULL,
    FLOW_NAME          VARCHAR2(180) NOT NULL,
    SEGMENT_LABEL      VARCHAR2(40),
    ACTIVE             CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_RMCF_FLOW_CODE UNIQUE (ORIGIN_ID, EMISSION_TYPE_ID, FLOW_CODE),
    CONSTRAINT UQ_RMCF_FLOW_CTX UNIQUE (FLOW_ID, ORIGIN_ID, EMISSION_TYPE_ID),
    CONSTRAINT FK_RMCF_FLOW_ORIGIN FOREIGN KEY (ORIGIN_ID) REFERENCES RM_CFACT_ORIGIN(ORIGIN_ID),
    CONSTRAINT FK_RMCF_FLOW_EMTYPE FOREIGN KEY (EMISSION_TYPE_ID) REFERENCES RM_CFACT_EMISSION_TYPE(EMISSION_TYPE_ID),
    CONSTRAINT CK_RMCF_FLOW_ACT CHECK (ACTIVE IN ('Y','N'))
);

CREATE TABLE RM_CFACT_SCOPE (
    SCOPE_ID          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SCOPE_CODE        VARCHAR2(100) NOT NULL,
    SCOPE_NAME        VARCHAR2(250) NOT NULL,
    ISSUER_ID         NUMBER NOT NULL,
    BUSINESS_ID       NUMBER NOT NULL,
    ORIGIN_ID         NUMBER NOT NULL,
    EMISSION_TYPE_ID  NUMBER NOT NULL,
    FLOW_ID           NUMBER,
    PRIORITY_ORDER    NUMBER DEFAULT 100 NOT NULL,
    ACTIVE            CHAR(1) DEFAULT 'Y' NOT NULL,
    VALID_FROM        DATE,
    VALID_TO          DATE,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_RMCF_SCOPE_CODE UNIQUE (SCOPE_CODE),
    CONSTRAINT FK_RMCF_SC_ISS FOREIGN KEY (ISSUER_ID) REFERENCES RM_CFACT_ISSUER(ISSUER_ID),
    CONSTRAINT FK_RMCF_SC_BUS FOREIGN KEY (BUSINESS_ID) REFERENCES RM_CFACT_BUSINESS(BUSINESS_ID),
    CONSTRAINT FK_RMCF_SC_ORIGIN FOREIGN KEY (ORIGIN_ID) REFERENCES RM_CFACT_ORIGIN(ORIGIN_ID),
    CONSTRAINT FK_RMCF_SC_EMTYPE FOREIGN KEY (EMISSION_TYPE_ID) REFERENCES RM_CFACT_EMISSION_TYPE(EMISSION_TYPE_ID),
    CONSTRAINT FK_RMCF_SC_FLOW_CTX FOREIGN KEY (FLOW_ID, ORIGIN_ID, EMISSION_TYPE_ID)
        REFERENCES RM_CFACT_FLOW(FLOW_ID, ORIGIN_ID, EMISSION_TYPE_ID),
    CONSTRAINT CK_RMCF_SC_ACT CHECK (ACTIVE IN ('Y','N')),
    CONSTRAINT CK_RMCF_SC_PRIO CHECK (PRIORITY_ORDER >= 0),
    CONSTRAINT CK_RMCF_SC_DATES CHECK (VALID_TO IS NULL OR VALID_FROM IS NULL OR VALID_TO >= VALID_FROM)
);

CREATE TABLE RM_CFACT_USER_SCOPE (
    USER_ID         NUMBER NOT NULL,
    SCOPE_ID        NUMBER NOT NULL,
    CAN_VIEW        CHAR(1) DEFAULT 'Y' NOT NULL,
    CAN_EXECUTE     CHAR(1) DEFAULT 'N' NOT NULL,
    CAN_CONFIGURE   CHAR(1) DEFAULT 'N' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_RMCF_USER_SCOPE PRIMARY KEY (USER_ID, SCOPE_ID),
    CONSTRAINT FK_RMCF_US_USER FOREIGN KEY (USER_ID) REFERENCES RM_CFACT_USER(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_RMCF_US_SCOPE FOREIGN KEY (SCOPE_ID) REFERENCES RM_CFACT_SCOPE(SCOPE_ID) ON DELETE CASCADE,
    CONSTRAINT CK_RMCF_US_VIEW CHECK (CAN_VIEW IN ('Y','N')),
    CONSTRAINT CK_RMCF_US_EXEC CHECK (CAN_EXECUTE IN ('Y','N')),
    CONSTRAINT CK_RMCF_US_CONF CHECK (CAN_CONFIGURE IN ('Y','N'))
);

CREATE INDEX IX_RMCF_ISS_COMP ON RM_CFACT_ISSUER(COMPANY_ID, ACTIVE);
CREATE INDEX IX_RMCF_FLOW_CTX ON RM_CFACT_FLOW(ORIGIN_ID, EMISSION_TYPE_ID, ACTIVE);
CREATE INDEX IX_RMCF_SC_CTX ON RM_CFACT_SCOPE(ISSUER_ID, BUSINESS_ID, ORIGIN_ID, EMISSION_TYPE_ID, FLOW_ID, ACTIVE);
CREATE INDEX IX_RMCF_US_SCOPE ON RM_CFACT_USER_SCOPE(SCOPE_ID, USER_ID);

