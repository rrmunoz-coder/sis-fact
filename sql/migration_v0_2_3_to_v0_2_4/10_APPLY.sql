CREATE TABLE RM_CFACT_EXECUTION_POLICY (
    POLICY_ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DATA_SOURCE_ID       NUMBER NOT NULL,
    EXECUTION_MODE       VARCHAR2(20) DEFAULT 'MANUAL' NOT NULL,
    FREQUENCY_TYPE       VARCHAR2(20),
    INTERVAL_VALUE       NUMBER DEFAULT 1 NOT NULL,
    RUN_TIME             VARCHAR2(5),
    DAY_OF_WEEK          NUMBER,
    DAY_OF_MONTH         NUMBER,
    TIMEOUT_MINUTES      NUMBER DEFAULT 45 NOT NULL,
    MAX_RETRIES          NUMBER DEFAULT 2 NOT NULL,
    EXTERNAL_EXECUTOR    VARCHAR2(120),
    ACTIVE               CHAR(1) DEFAULT 'Y' NOT NULL,
    LAST_DUE_AT          TIMESTAMP,
    NEXT_DUE_AT          TIMESTAMP,
    CREATED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY           VARCHAR2(120),
    UPDATED_AT           TIMESTAMP,
    UPDATED_BY           VARCHAR2(120),
    CONSTRAINT UQ_RMCF_EXPOL_SRC UNIQUE (DATA_SOURCE_ID),
    CONSTRAINT FK_RMCF_EXPOL_SRC FOREIGN KEY (DATA_SOURCE_ID)
        REFERENCES RM_CFACT_DATA_SOURCE(DATA_SOURCE_ID) ON DELETE CASCADE,
    CONSTRAINT CK_RMCF_EXPOL_MODE CHECK (EXECUTION_MODE IN ('MANUAL','SCHEDULED','EXTERNAL')),
    CONSTRAINT CK_RMCF_EXPOL_FREQ CHECK (FREQUENCY_TYPE IS NULL OR FREQUENCY_TYPE IN ('MINUTES','HOURLY','DAILY','WEEKLY','MONTHLY')),
    CONSTRAINT CK_RMCF_EXPOL_INTERVAL CHECK (INTERVAL_VALUE >= 1),
    CONSTRAINT CK_RMCF_EXPOL_DOW CHECK (DAY_OF_WEEK IS NULL OR DAY_OF_WEEK BETWEEN 1 AND 7),
    CONSTRAINT CK_RMCF_EXPOL_DOM CHECK (DAY_OF_MONTH IS NULL OR DAY_OF_MONTH BETWEEN 1 AND 31),
    CONSTRAINT CK_RMCF_EXPOL_TIMEOUT CHECK (TIMEOUT_MINUTES BETWEEN 1 AND 1440),
    CONSTRAINT CK_RMCF_EXPOL_RETRY CHECK (MAX_RETRIES BETWEEN 0 AND 10),
    CONSTRAINT CK_RMCF_EXPOL_ACT CHECK (ACTIVE IN ('Y','N'))
);

CREATE TABLE RM_CFACT_EXECUTION_QUEUE (
    QUEUE_ID             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DATA_SOURCE_ID       NUMBER NOT NULL,
    POLICY_ID            NUMBER,
    SCOPE_ID             NUMBER NOT NULL,
    REQUEST_TYPE         VARCHAR2(20) NOT NULL,
    REQUEST_KEY          VARCHAR2(240),
    STATUS               VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    ATTEMPT_NO           NUMBER DEFAULT 0 NOT NULL,
    MAX_ATTEMPTS         NUMBER DEFAULT 1 NOT NULL,
    AVAILABLE_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    REQUESTED_AT         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    REQUESTED_BY         VARCHAR2(120),
    STARTED_AT           TIMESTAMP,
    FINISHED_AT          TIMESTAMP,
    WORKER_ID            VARCHAR2(120),
    EXTRACTION_ID        NUMBER,
    ERROR_MESSAGE        VARCHAR2(4000),
    CREATED_AT           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_RMCF_EXQ_REQKEY UNIQUE (REQUEST_KEY),
    CONSTRAINT FK_RMCF_EXQ_SRC FOREIGN KEY (DATA_SOURCE_ID)
        REFERENCES RM_CFACT_DATA_SOURCE(DATA_SOURCE_ID),
    CONSTRAINT FK_RMCF_EXQ_POLICY FOREIGN KEY (POLICY_ID)
        REFERENCES RM_CFACT_EXECUTION_POLICY(POLICY_ID),
    CONSTRAINT FK_RMCF_EXQ_SCOPE FOREIGN KEY (SCOPE_ID)
        REFERENCES RM_CFACT_SCOPE(SCOPE_ID),
    CONSTRAINT FK_RMCF_EXQ_RUN FOREIGN KEY (EXTRACTION_ID)
        REFERENCES RM_CFACT_EXTRACTION_RUN(EXTRACTION_ID),
    CONSTRAINT CK_RMCF_EXQ_TYPE CHECK (REQUEST_TYPE IN ('MANUAL','SCHEDULED','EXTERNAL')),
    CONSTRAINT CK_RMCF_EXQ_STATUS CHECK (STATUS IN ('PENDING','RUNNING','SUCCESS','WARNING','ERROR','CANCELLED')),
    CONSTRAINT CK_RMCF_EXQ_ATTEMPT CHECK (ATTEMPT_NO >= 0 AND MAX_ATTEMPTS >= 1)
);

CREATE INDEX IX_RMCF_EXPOL_DUE
    ON RM_CFACT_EXECUTION_POLICY(ACTIVE, EXECUTION_MODE, NEXT_DUE_AT);
CREATE INDEX IX_RMCF_EXQ_PICK
    ON RM_CFACT_EXECUTION_QUEUE(STATUS, AVAILABLE_AT, REQUESTED_AT);
CREATE INDEX IX_RMCF_EXQ_SOURCE
    ON RM_CFACT_EXECUTION_QUEUE(DATA_SOURCE_ID, SCOPE_ID, REQUESTED_AT);

INSERT INTO RM_CFACT_EXECUTION_POLICY (
    DATA_SOURCE_ID, EXECUTION_MODE, TIMEOUT_MINUTES, MAX_RETRIES, ACTIVE, CREATED_BY
)
SELECT D.DATA_SOURCE_ID, 'MANUAL', 45, 2, 'Y', 'MIGRATION_V024'
FROM RM_CFACT_DATA_SOURCE D
WHERE NOT EXISTS (
    SELECT 1 FROM RM_CFACT_EXECUTION_POLICY P
    WHERE P.DATA_SOURCE_ID=D.DATA_SOURCE_ID
);

COMMENT ON TABLE RM_CFACT_EXECUTION_POLICY IS 'Política administrable de ejecución/espera por insumo.';
COMMENT ON TABLE RM_CFACT_EXECUTION_QUEUE IS 'Cola de solicitudes de ejecución por insumo y scope.';

