   BILLING ONE / SIS-FACT
   MIGRACION v0.1 -> v0.2
   PASO 1 - PREPARAR Y LIMPIAR MODELO v0.1

   VERSION DBEAVER - SQL ORACLE PLANO
   - Sin DECLARE / BEGIN / END
   - Sin separador /
   - Sin comandos SQL*Plus
   - SISGAV2 NO SE TOCA

   Evidencia validada el 11-08-2026:
   - 10 tablas v0.1/legacy con 0 filas
   - RM_CFACT_USER con 1 fila

   IMPORTANTE:
   Ejecutar primero las consultas PRECHECK. Si no coinciden con lo esperado,
   NO ejecutar el bloque destructivo.
